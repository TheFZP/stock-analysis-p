/** 日期 → 假期名（构建一次，O(1) 查找） */
const HK_HOLIDAY_MAP = new Map();
for (const list of Object.values(HK_HOLIDAY_TABLE)) {
  for (const [date, name] of list) HK_HOLIDAY_MAP.set(date, name);
}

/** 已完整覆盖的年份（升序） */
export const HK_HOLIDAY_YEARS = Object.keys(HK_HOLIDAY_TABLE)
  .map(Number)
  .sort((a, b) => a - b);

/**
 * 判断某日是否为港股休市日（公众假期）
 * @param {string} dateStr "yyyy-MM-dd"
 * @returns {boolean|null} null = 该年份未收录（未知，调用方退回「周一至周五」判定）
 */
export function isHKHoliday(dateStr) {
  if (!dateStr) return null;
  const year = Number(String(dateStr).slice(0, 4));
  if (!HK_HOLIDAY_TABLE[year]) return null;
  return HK_HOLIDAY_MAP.has(dateStr);
}

/** 假期名（非假期返回空串） */
export function getHKHolidayName(dateStr) {
  return HK_HOLIDAY_MAP.get(dateStr) || "";
}
